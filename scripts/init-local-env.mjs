#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';

const repoRoot = process.cwd();
const outputPath = path.join(repoRoot, '.env.local');
const apiKeysPath = path.join(repoRoot, 'API_Keys.txt');
const args = new Set(process.argv.slice(2));

const shouldForce = args.has('--force');
const shouldPrint = args.has('--stdout') || args.has('--print');
const shouldPrintSecrets = args.has('--print-secrets');

const existingOutput = fs.existsSync(outputPath);
if (existingOutput && !shouldForce && !shouldPrint) {
  console.error('.env.local already exists. Use --force to overwrite or --stdout to print.');
  process.exit(1);
}

const odooApiKey = readKey('Odoo API Key');
const template = buildTemplate({
  odooApiKey: shouldPrint && !shouldPrintSecrets
    ? odooApiKey
      ? '<REDACTED>'
      : ''
    : odooApiKey,
});

if (shouldPrint) {
  process.stdout.write(template);
  process.exit(0);
}

fs.writeFileSync(outputPath, template, 'utf8');
console.log(`Wrote ${path.relative(repoRoot, outputPath)}`);

function readKey(label) {
  if (!fs.existsSync(apiKeysPath)) {
    return '';
  }

  const content = fs.readFileSync(apiKeysPath, 'utf8');
  const matcher = new RegExp(`^${escapeRegExp(label)}:\\s*(.+)$`, 'im');
  const match = content.match(matcher);
  return match?.[1]?.trim() ?? '';
}

function buildTemplate({ odooApiKey }) {
  return [
    '# Generated by scripts/init-local-env.mjs',
    '# Update the Bakki Core DB and Spaces values for your environment.',
    '',
    'VITE_API_BASE_URL=/api/v1',
    '',
    'ODOO_URL=https://bakki.odoo.com',
    'ODOO_DB=bakki',
    `ODOO_API_KEY=${odooApiKey}`,
    '',
    '# Local Bakki Core defaults',
    'BAKKI_CORE_DB_HOST=127.0.0.1',
    'BAKKI_CORE_DB_PORT=5432',
    'BAKKI_CORE_DB_NAME=bakki_core',
    'BAKKI_CORE_DB_USER=postgres',
    'BAKKI_CORE_DB_PASSWORD=postgres',
    'BAKKI_CORE_DB_SSL=false',
    '',
    '# Local media storage for development',
    'MEDIA_PROVIDER=local-filesystem',
    'LOCAL_MEDIA_ROOT=.local/media',
    '',
    '# DigitalOcean Spaces',
    'SPACES_BUCKET=',
    'SPACES_ENDPOINT=',
    'SPACES_REGION=',
    'SPACES_KEY=',
    'SPACES_SECRET=',
    'SPACES_CDN_BASE_URL=',
    '',
  ].join('\n');
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
